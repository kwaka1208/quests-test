import argparse
import os
import sys

VERSION = "2.3.0"


def save(args):
    title = "café menu"  # the title has an accent: e with ' on top
    encoding = os.environ.get("NOTES_ENCODING", "ascii").lower().replace("-", "")
    if encoding != "utf8":
        print("Traceback (most recent call last):", file=sys.stderr)
        print('  File "notes.py", line 14, in save', file=sys.stderr)
        print("UnicodeEncodeError: 'ascii' codec can't encode character '\\xe9' in position 3",
              file=sys.stderr)
        return 1
    print(f"Saved a note with {len(title)} characters in the title.")
    print("Code word: paper")
    return 0


def list_notes(args):
    if args.pinned:
        print("Error: pinned notes are not supported yet (code: lamp)", file=sys.stderr)
        return 1
    if args.color:
        print("Error: --color is not supported (code: apple)", file=sys.stderr)
        return 1
    if args.sort == "size":
        print("Error: cannot sort by size (code: pencil)", file=sys.stderr)
        return 1
    if args.sort == "title":
        print("Error: sorting by title is broken (code: river)", file=sys.stderr)
        return 1
    print("You have 3 notes.")
    return 0


def main():
    parser = argparse.ArgumentParser(description="A tiny note-taking tool.")
    parser.add_argument("--version", action="store_true", help="show the version")
    sub = parser.add_subparsers(dest="command")
    sub.add_parser("save", help="save a note").set_defaults(func=save)
    lst = sub.add_parser("list", help="list your notes")
    lst.add_argument("--sort", choices=["date", "title", "size"], default="date", help="sort order")
    lst.add_argument("--pinned", action="store_true", help="show only pinned notes")
    lst.add_argument("--color", action="store_true", help="use colors")
    lst.set_defaults(func=list_notes)
    args = parser.parse_args()
    if args.version:
        print(f"notes {VERSION} (code: stone)")
        return 0
    if not args.command:
        parser.print_help()
        return 0
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
