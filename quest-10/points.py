"""Lunch points of Northwind. You get half of the price as points.

Run: python points.py
Do not edit this file. Something here looks strange. Ask about it in question.md.
"""


def points(price):
    return round(price * 0.5)


def main():
    for price in (3, 5, 7):
        print(f"A {price}-dollar lunch gives {points(price)} points.")


if __name__ == "__main__":
    main()
