"""Tip splitter from Northwind's lunch app.

Usage: python tip.py BILL PEOPLE
It adds a 10% tip to the bill, and shows how much each person pays.

This script has a bug. Find it, and report it in issue.md.
Do not edit this file.
"""
import sys


def main():
    if len(sys.argv) != 3:
        print("Usage: python tip.py BILL PEOPLE")
        return 2
    bill = float(sys.argv[1])
    people = int(sys.argv[2])
    total = bill * 1.10
    share = total / people
    print(f"Total with tip: {total:.2f}")
    print(f"Each person pays: {share:.2f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
