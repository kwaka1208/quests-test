def weekly_bonus(points, day):
    """Return the points with the weekly bonus.

    Args:
        points (int): The points before the bonus.
        day (str): The day of the week, in three small letters, like "mon" or "fri".

    Returns:
        int: The points after the bonus. On "fri", the points are doubled.
    """
    return points * 2 if day == "fri" else points


