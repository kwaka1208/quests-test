import warnings

# NOTE: All prices in this module are in dollars (5 means 5 dollars). Do not pass cents.

# Max 3 items per order.
MAX_ITEMS = 5


def points_for(price):
    """Return the points for one lunch.

    Args:
        price (float): The price of the lunch in dollars, not in cents.
            For example, 5 means 5 dollars.

    Returns:
        int: The points. The customer gets half of the price as points.

    Raises:
        ValueError: If price is negative.
    """
    if price < 0:
        raise ValueError("price must not be negative")
    # FIXME: A 5-dollar lunch gives only 2 points. See issue #52. (Kaito)
    return round(price * 0.5)


