def make_order(items):
    """Make an order from a list of items.

    Args:
        items (list of str): The names of the items, like ["salad", "coffee"].

    Returns:
        dict: The order.

    Raises:
        ValueError: If there are too many items.
    """
    # An order can have 3 items or less.
    if len(items) > MAX_ITEMS:
        raise ValueError(f"too many items: {len(items)}")
    return {"items": list(items)}
