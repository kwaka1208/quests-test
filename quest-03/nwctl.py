"""nwctl - the control tool of Northwind. It works only when you call it in the right way.

Do not edit this file. Read its help instead:

  python nwctl.py --help
"""
import argparse
import base64
import sys

LOGS = {"quiet": "(no messages)", "normal": "Starting...", "verbose": "Starting... loading... connecting..."}
APPROVER = "misaki"
WORD = "bGF1bmNo"


def build_parser():
    parser = argparse.ArgumentParser(
        prog="nwctl.py",
        description="The control tool of Northwind. It works only when you call it in the right way.",
    )
    parser.add_argument("--log", choices=sorted(LOGS), default="quiet",
                        help="how much the tool tells you (default: %(default)s)")
    commands = parser.add_subparsers(dest="command", required=True, title="commands")

    commands.add_parser("status", help="show the status of the servers",
                        description="Show the status of the servers.")

    deploy = commands.add_parser("deploy", help="send the app to a server",
                                 description="Send the app to a server. Every deploy needs approval.")
    mode = deploy.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="only show what would happen")
    mode.add_argument("--now", action="store_true", help="do not wait for the next release time")
    deploy.add_argument("--approved-by", metavar="NAME",
                        help="the name of the person who approved this deploy "
                             "(the senior engineer who welcomed you on your first day)")
    deploy.add_argument("server", choices=["staging", "production"], help="where to send the app")
    return parser


def status(args):
    print("staging: running")
    print("production: running")
    return 0


def deploy(args):
    print(f"Deploy to {args.server}.")
    if args.now:
        print("No waiting.")
    elif args.dry_run:
        print("This is a dry run. Nothing will change.")
    if args.approved_by is None:
        print("The deploy needs approval. Nobody approved it, so it stops here.")
        return 1
    if args.approved_by.strip().lower() != APPROVER:
        print(f"'{args.approved_by}' cannot approve this deploy. It stops here.")
        return 1
    print("Approved. The deploy is on its way.")
    print(f"The word is: {base64.b64decode(WORD).decode()}")
    return 0


def main():
    args = build_parser().parse_args()
    if LOGS[args.log] != "(no messages)":
        print(LOGS[args.log])
    return status(args) if args.command == "status" else deploy(args)


if __name__ == "__main__":
    sys.exit(main())
