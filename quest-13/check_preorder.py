"""Test for place_preorder() in the 'history' folder. Run: python check_preorder.py

Do not edit this file.
"""
import importlib.util
import sys
from pathlib import Path

path = Path(__file__).resolve().parent / "history" / "orders.py"
if not path.exists():
    sys.exit("There is no history yet. Run: python history.py --setup")
spec = importlib.util.spec_from_file_location("orders", path)
orders = importlib.util.module_from_spec(spec)
spec.loader.exec_module(orders)

print(f"MAX_PREORDERS is {orders.MAX_PREORDERS}. Placing {orders.MAX_PREORDERS} pre-orders...")
try:
    for n in range(orders.MAX_PREORDERS):
        orders.place_preorder(f"lunch {n + 1}", "tomorrow")
except ValueError as err:
    print(f"FAILED: pre-order {n + 1} was refused ({err}).")
    print(f"It should be possible to place {orders.MAX_PREORDERS} pre-orders.")
    sys.exit(1)
print("OK: all pre-orders were placed.")
