"""The history of main after Pull Request #57 was merged: a small git repository with five commits.

  python history.py --setup   make the history (or make it again from the start)

Do not edit this file.
"""
import argparse
import base64
import os
import shutil
import stat
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE / "history"

STEP1 = '''"""Orders of Northwind Lunch."""
MAX_PREORDERS = 30  # in settings.py in the real app
PREORDERS = []


def place_preorder(item, day):
    if len(PREORDERS) >= MAX_PREORDERS:
        raise ValueError("too many pre-orders")
    PREORDERS.append((item, day))
    return f"Your {item} will be ready on {day}."
'''
STEP2 = STEP1.replace("will be ready on {day}.", "will be redy on {day}, at the counter.")
STEP4 = STEP2.replace("if len(PREORDERS) >= MAX_PREORDERS:", "if len(PREORDERS) >= MAX_PREORDERS - 1:")
STEP5 = STEP4.replace("will be redy on", "will be ready on")
COMMITS = [
    ("Haruto", "feat: add pre-orders (#57)", STEP1, None, "bWFwbGU="),
    ("Yui", "feat: tell the customer where to pick up", STEP2, None, "Y2VkYXI="),
    ("Haruka", "docs: explain pre-orders in the README", STEP2, "Pre-orders: order the day before.\n", "d2lsbG93"),
    ("Daiki", "refactor: make the limit check easier to read", STEP4, None, "YmlyY2g="),
    ("Kaito", "fix: correct a typo in a message", STEP5, None, "YXNwZW4="),
]


def git(*args, who="Haruto", date=None):
    cmd = ["git", "-C", str(REPO), "-c", f"user.name={who}", "-c", f"user.email={who.lower()}@northwind.invalid",
           "-c", "commit.gpgsign=false", "-c", "core.autocrlf=false", *args]
    env = dict(os.environ)
    if date:
        env.update(GIT_AUTHOR_DATE=date, GIT_COMMITTER_DATE=date)
    result = subprocess.run(cmd, capture_output=True, text=True, env=env)
    if result.returncode != 0:
        sys.exit(f"git {' '.join(args)} が失敗しました:\n{result.stderr}")
    return result


def remove_readonly(func, path, _):
    os.chmod(path, stat.S_IWRITE)
    func(path)


def setup():
    if REPO.exists():
        if sys.version_info >= (3, 12):
            shutil.rmtree(REPO, onexc=remove_readonly)
        else:
            shutil.rmtree(REPO, onerror=remove_readonly)
    REPO.mkdir()
    git("init", "-q")
    git("symbolic-ref", "HEAD", "refs/heads/main")
    for number, (who, message, code, readme, word) in enumerate(COMMITS):
        (REPO / "orders.py").write_text(code, encoding="utf-8", newline="\n")
        if readme:
            (REPO / "README.md").write_text(readme, encoding="utf-8", newline="\n")
        else:
            (REPO / "README.md").touch()
        git("add", "-A")
        word = base64.b64decode(word).decode()
        git("commit", "-q", "-m", message, "-m", f"Code word: {word}",
            who=who, date=f"2026-11-0{number + 2}T10:00:00+09:00")
    print("'history' フォルダに履歴を用意しました。コミットは5個あります。")
    print()
    print("次にすること:")
    print("    python check_preorder.py      （失敗します）")
    print("    cd history")
    print("    git log -p")


def main():
    parser = argparse.ArgumentParser(description="Make the history of the pre-order branch.")
    parser.add_argument("--setup", action="store_true", help="make the history again from the start")
    args = parser.parse_args()
    if shutil.which("git") is None:
        print("git が見つかりません。Codespaces を使ってください。")
        return 1
    if args.setup:
        setup()
        return 0
    parser.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())
